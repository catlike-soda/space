let _locale = "ja";

function t(key) {
  return (I18N[_locale] && I18N[_locale][key]) || I18N["ja"][key] || key;
}

function setLocale(loc) {
  if (I18N[loc]) {
    _locale = loc;
    LocalCache.saveSetting("locale", loc);
    document.documentElement.lang = loc === "ja" ? "ja" : "zh-CN";
  }
}

function getLocale() {
  return _locale;
}

function getDefaultSearchLang() {
  return _locale === "ja" ? "kr_ja" : "kr";
}

async function loadLocale() {
  const saved = await LocalCache.get("settings", "locale");
  if (saved && I18N[saved.value]) {
    _locale = saved.value;
  }
  document.documentElement.lang = _locale === "ja" ? "ja" : "zh-CN";
}
